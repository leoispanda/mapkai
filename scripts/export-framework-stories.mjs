import { readdir, readFile, writeFile } from 'node:fs/promises';
import { frameworks } from '../toolbox/frameworks/data.js';
import { references } from '../toolbox/frameworks/references.js';

const root = new URL('../', import.meta.url);
const generatedRoot = new URL('content/framework-stories/', root);
const output = new URL('toolbox/frameworks/framework-stories.js', root);
const requiredStrings = ['framework', 'title', 'teaser', 'concept', 'explanation', 'boundary', 'reflection', 'mode'];
const frameworkIds = new Set(frameworks.map(framework => framework.id));
const referenceIds = new Set(references.map(reference => reference.id));

function cleanCalculation(calculation, id, language) {
  if (calculation === undefined) return undefined;
  if (typeof calculation === 'string') {
    if (!calculation.trim()) throw new Error(`${id}/${language}: calculation must not be empty`);
    return calculation.trim();
  }
  if (!calculation || Array.isArray(calculation) || typeof calculation !== 'object') {
    throw new Error(`${id}/${language}: calculation must be a string or a non-empty object`);
  }
  const entries = Object.entries(calculation);
  if (!entries.length) throw new Error(`${id}/${language}: calculation object must not be empty`);
  for (const [key, value] of entries) {
    if (!key.trim() || typeof value !== 'string' || !value.trim()) {
      throw new Error(`${id}/${language}: calculation object must contain non-empty string values`);
    }
  }
  return Object.fromEntries(entries.map(([key, value]) => [key, value.trim()]));
}

function calculationShape(calculation) {
  if (calculation === undefined) return 'none';
  if (typeof calculation === 'string') return 'string';
  return `object:${Object.keys(calculation).length}`;
}

function cleanStory(story, id, language) {
  if (!frameworkIds.has(id)) throw new Error(`${id}/${language}: unknown framework id`);
  if (story.framework !== id) throw new Error(`${id}/${language}: framework must match directory name`);
  for (const field of requiredStrings) {
    if (typeof story[field] !== 'string' || !story[field].trim()) throw new Error(`${id}/${language}: missing ${field}`);
  }
  for (const field of ['paragraphs', 'mapping', 'refs']) {
    if (!Array.isArray(story[field]) || !story[field].length || story[field].some(value => typeof value !== 'string' || !value.trim())) {
      throw new Error(`${id}/${language}: ${field} must be a non-empty string array`);
    }
  }
  for (const ref of story.refs) if (!referenceIds.has(ref)) throw new Error(`${id}/${language}: unknown reference id ${ref}`);
  const calculation = cleanCalculation(story.calculation, id, language);
  return {
    framework: story.framework,
    title: story.title,
    teaser: story.teaser,
    paragraphs: story.paragraphs,
    concept: story.concept,
    explanation: story.explanation,
    mapping: story.mapping,
    boundary: story.boundary,
    reflection: story.reflection,
    refs: story.refs,
    mode: story.mode,
    ...(calculation === undefined ? {} : { calculation }),
  };
}

async function optionalStory(directory, language) {
  try {
    const source = await readFile(new URL(`${directory}/story.${language}.json`, generatedRoot), 'utf8');
    return cleanStory(JSON.parse(source), directory, language);
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
}

const entries = {};
for (const directory of (await readdir(generatedRoot, { withFileTypes: true }))
  .filter(entry => entry.isDirectory() && !entry.name.startsWith('_'))
  .map(entry => entry.name)
  .sort()) {
  const zh = await optionalStory(directory, 'zh');
  const en = await optionalStory(directory, 'en');
  if (zh && en && calculationShape(zh.calculation) !== calculationShape(en.calculation)) {
    throw new Error(`${directory}: zh/en calculation structures must match`);
  }
  if (zh || en) entries[directory] = { ...(zh ? { zh } : {}), ...(en ? { en } : {}) };
}

const source = `// Generated by scripts/export-framework-stories.mjs from canonical published story JSON files.\n` +
  `// Edit content/framework-stories/<framework-id>/story.<language>.json, then rebuild.\n` +
  `export const frameworkStories = ${JSON.stringify(entries, null, 2)};\n\n` +
  `export function frameworkStoryFor(frameworkId, language) {\n` +
  `  return frameworkStories[frameworkId]?.[language] || null;\n` +
  `}\n`;

await writeFile(output, source);
console.log(`Exported ${Object.keys(entries).length} framework story records.`);
